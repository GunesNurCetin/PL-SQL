-- 3. BANKING PACKAGE SPECIFICATION (Paket Tanımı)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE PACKAGE pkg_bank_ops AS
    -- Özel Hata: Yetersiz bakiye durumu için tanımlanmıştır.
    insufficient_funds EXCEPTION;
    PRAGMA EXCEPTION_INIT(insufficient_funds, -20001);

    -- Transfer Prosedürü: Kaynak ve hedef hesap arasında güvenli transfer sağlar.
    PROCEDURE transfer_money(
        p_from_acc IN NUMBER,
        p_to_acc   IN NUMBER,
        p_amount   IN NUMBER
    );
END pkg_bank_ops;
/

-- 4. BANKING PACKAGE BODY (Paket Mantığı)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE PACKAGE BODY pkg_bank_ops AS
    PROCEDURE transfer_money(
        p_from_acc IN NUMBER,
        p_to_acc   IN NUMBER,
        p_amount   IN NUMBER
    ) IS
        v_current_balance NUMBER;
    BEGIN
        -- [Bakiye Kontrolü & Kilitleme]
        -- 'FOR UPDATE' kullanılarak işlem sırasında verinin değişmesi engellenir.
        SELECT balance INTO v_current_balance 
        FROM accounts 
        WHERE account_id = p_from_acc 
        FOR UPDATE;

        IF v_current_balance < p_amount THEN
            RAISE_APPLICATION_ERROR(-20001, 'Bakiye Yetersiz! Mevcut: ' || v_current_balance);
        END IF;

        -- [Transfer İşlemi]
        -- Gönderen hesaptan düş, alıcı hesaba ekle.
        UPDATE accounts SET balance = balance - p_amount WHERE account_id = p_from_acc;
        UPDATE accounts SET balance = balance + p_amount WHERE account_id = p_to_acc;

        -- [Başarılı İşlem Loglama]
        INSERT INTO transaction_logs (account_id, action_type, amount, status_message)
        VALUES (p_from_acc, 'TRANSFER_OUT', p_amount, 'SUCCESSFUL');

        COMMIT; -- Tüm işlemler başarılıysa kalıcı hale getir.
        DBMS_OUTPUT.PUT_LINE('Islem onaylandi: ' || p_amount || ' transfer edildi.');

    EXCEPTION
        WHEN OTHERS THEN
            -- Bir hata oluşursa (veritabanı hatası veya yetersiz bakiye)
            -- Yapılan tüm finansal değişiklikleri geri al (Rollback).
            ROLLBACK; 
            
            -- Hatayı log tablosuna kaydet (Otonom loglama simülasyonu).
            INSERT INTO transaction_logs (account_id, action_type, amount, status_message)
            VALUES (p_from_acc, 'TRANSFER_FAILED', p_amount, SUBSTR(SQLERRM, 1, 200));
            COMMIT;
            DBMS_OUTPUT.PUT_LINE('Hata: ' || SQLERRM);
    END transfer_money;
END pkg_bank_ops;
/

