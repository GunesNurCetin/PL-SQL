-- 1. SCHEMA SETUP (Tablo Yapılandırması)
-- -----------------------------------------------------------------------------
-- 'accounts' tablosu müşteri bakiyelerini tutar. 
-- 'transaction_logs' tüm işlem geçmişini ve hataları izlemek için kullanılır.

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE transaction_logs';
    EXECUTE IMMEDIATE 'DROP TABLE accounts';
EXCEPTION WHEN OTHERS THEN NULL; END;
/

CREATE TABLE accounts (
    account_id NUMBER PRIMARY KEY,
    account_holder VARCHAR2(100) NOT NULL,
    balance NUMBER(15, 2) DEFAULT 0 CHECK (balance >= 0) -- Negatif bakiye kontrolü
);

CREATE TABLE transaction_logs (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id NUMBER,
    action_type VARCHAR2(50),
    amount NUMBER(15, 2),
    log_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status_message VARCHAR2(255)
);

