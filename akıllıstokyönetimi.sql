-- 1. SCHEMA SETUP (Tablo Yapılandırması)
-- -----------------------------------------------------------------------------
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE supply_requests';
    EXECUTE IMMEDIATE 'DROP TABLE sales_history';
    EXECUTE IMMEDIATE 'DROP TABLE products';
EXCEPTION WHEN OTHERS THEN NULL; END;
/

CREATE TABLE products (
    product_id NUMBER PRIMARY KEY,
    product_name VARCHAR2(100),
    stock_quantity NUMBER DEFAULT 0,
    min_threshold NUMBER DEFAULT 10, -- Kritik stok sınırı
    unit_price NUMBER(10, 2)
);

CREATE TABLE sales_history (
    sale_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id NUMBER REFERENCES products(product_id),
    quantity_sold NUMBER,
    sale_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE supply_requests (
    request_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id NUMBER,
    request_amount NUMBER,
    request_date DATE DEFAULT SYSDATE,
    status VARCHAR2(20) DEFAULT 'PENDING'
);

